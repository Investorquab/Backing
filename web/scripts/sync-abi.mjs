// Regenerates src/lib/abi.ts from Foundry build output. Run after changing contracts:
//   cd contracts && forge build && cd ../web && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
const read = (n) => JSON.parse(readFileSync(new URL(`../../contracts/out/${n}.sol/${n}.json`, import.meta.url))).abi;
const out = `// Generated by scripts/sync-abi.mjs — do not edit by hand.
export const backingAbi = ${JSON.stringify(read("Backing"), null, 2)} as const;

export const mockUsdcAbi = ${JSON.stringify(read("MockUSDC"), null, 2)} as const;

export const demoVaultAbi = ${JSON.stringify(read("MockYieldVault").filter((x) => ["aprBps", "convertToAssets", "totalAssets"].includes(x.name)), null, 2)} as const;
`;
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), out);
console.log("wrote src/lib/abi.ts");
